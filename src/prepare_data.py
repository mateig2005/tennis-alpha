"""Load, combine, inspect and clean ATP match CSVs.

Run from the project root:  python src/prepare_data.py
Reads  data/raw/atp_matches_*.csv   (see src/download_data.py)
Writes data/processed/atp_matches_{clean,dev,locked}.csv and reports/data_report.md
"""
import glob
import json
from pathlib import Path

import pandas as pd

RAW, OUT, REPORT = Path("data/raw"), Path("data/processed/atp_matches_clean.csv"), Path("reports/data_report.md")
# Physical lock (PLAN.md section 8): modelling code reads only the dev file; test + forward_oos live in the locked file.
DEV_OUT, LOCKED_OUT = Path("data/processed/atp_matches_dev.csv"), Path("data/processed/atp_matches_locked.csv")
DEV_SPLITS = {"warmup", "train", "validation"}

# Dates are tournament START dates (usually a Monday), not match dates. Within a tournament the
# only time signal is the round. Equal rank = no known order (round robin, bronze-medal vs final).
ROUND_RANK = {"RR": 0, "R128": 1, "R64": 2, "R32": 3, "R16": 4, "QF": 5, "SF": 6, "BR": 7, "F": 7}

# Chronological design. Boundaries use the tournament-start year, so a tournament is never split.
SPLITS = [(2010, 2014, "warmup"), (2015, 2023, "train"), (2024, 2024, "validation"),
          (2025, 2025, "test"), (2026, 2026, "forward_oos")]

# Describe the match being predicted -> usable ONLY as lagged history from earlier matches.
POST_MATCH_COLS = ["score", "minutes"] + [f"{p}_{s}" for p in "wl" for s in
                   ["ace", "df", "svpt", "1stIn", "1stWon", "2ndWon", "SvGms", "bpSaved", "bpFaced"]]

NOT_PLAYED = r"w/o|walkover|def|abandon|unfinished|unp|abn"  # no valid result; 'RET' is kept (flagged)


def load():
    files = sorted(glob.glob(str(RAW / "atp_matches_*.csv")))
    df = pd.concat([pd.read_csv(f, dtype={"tourney_date": str}).assign(season_file=int(f[-8:-4])) for f in files],
                   ignore_index=True)
    return df, len(files)


def main():
    df, n_files = load()
    manifest = json.loads((RAW / "manifest.json").read_text())
    lines = [f"# Data report (auto-generated by src/prepare_data.py)\n",
             f"Source: `{manifest['repo']}` (Hugging Face), commit `{manifest['commit']}`; {n_files} yearly files.\n",
             f"Raw rows: **{len(df):,}**\n"]
    log = lines.append

    # --- dates -------------------------------------------------------------
    df["tourney_date"] = pd.to_datetime(df["tourney_date"], format="%Y%m%d")  # raises if any date is invalid
    mism = df[df.tourney_date.dt.year != df.season_file]
    log(f"\n## Dates\n- Range of tourney_date: {df.tourney_date.min().date()} to {df.tourney_date.max().date()}\n"
        f"- Rows whose date year != file year: {len(mism)} (all dated earlier than the file year: "
        f"{bool((mism.tourney_date.dt.year < mism.season_file).all())}; late-December starts of the next season)\n"
        f"- tourney_id with >1 start date: {int((df.groupby('tourney_id').tourney_date.nunique() > 1).sum())}\n")

    # --- duplicates --------------------------------------------------------
    key = ["tourney_id", "round", "winner_id", "loser_id"]
    flipped = df.merge(df, left_on=key, right_on=["tourney_id", "round", "loser_id", "winner_id"])
    log(f"## Duplicates\n- Exact duplicate rows: {df.duplicated(subset=[c for c in df if c != 'season_file']).sum()}\n"
        f"- Duplicate (tourney_id, match_num): {df.duplicated(['tourney_id', 'match_num']).sum()}\n"
        f"- Duplicate (tourney, round, winner, loser): {df.duplicated(key).sum()}\n"
        f"- Same pair, same round, both directions: {len(flipped)} "
        f"(round-robin repeats and Davis Cup ties can legitimately repeat; inspect if >0)\n")

    # --- completed matches --------------------------------------------------
    not_played = df.score.str.lower().str.contains(NOT_PLAYED, regex=True, na=True)
    log(f"## Completed matches\n- Dropped (walkover / default / abandoned / no score): {int(not_played.sum())}\n"
        f"- Kept but flagged `retired` (RET): {int(df.score.str.contains('RET', na=False).sum())}\n")
    df = df[~not_played].copy()
    df["retired"] = df.score.str.contains("RET")

    # --- fixes found by inspection ------------------------------------------
    dup = df.duplicated(key + ["score"])  # Davis Cup ties listed twice under different match_num
    df = df[~dup].copy()
    bad = {c: int(((df[c] < 150) | (df[c] > 230)).sum()) for c in ["winner_ht", "loser_ht"]}
    for c in bad:  # data-entry errors (3, 15, 71 cm): set to missing rather than guess
        df.loc[(df[c] < 150) | (df[c] > 230), c] = float("nan")
    log(f"## Fixes\n- Dropped duplicate matches (same tourney, round, players, score): {int(dup.sum())}\n"
        f"- Implausible heights set to NaN: {bad}\n")

    # --- consistency checks -------------------------------------------------
    unknown = set(df["round"]) - set(ROUND_RANK)
    assert not unknown, f"unknown rounds {unknown}"
    ids = pd.concat([df[["winner_id", "winner_name"]].set_axis(["id", "name"], axis=1),
                     df[["loser_id", "loser_name"]].set_axis(["id", "name"], axis=1)])
    log(f"## Consistency\n- Player ids with >1 name: {int((ids.groupby('id').name.nunique() > 1).sum())}\n"
        f"- winner == loser: {int((df.winner_id == df.loser_id).sum())}\n"
        f"- best_of not in {{3,5}}: {int((~df.best_of.isin([3, 5])).sum())}\n"
        f"- Ranks <= 0: {int(((df.winner_rank <= 0) | (df.loser_rank <= 0)).sum())}\n"
        f"- Player age outside 14-50: {int(((df.winner_age < 14) | (df.winner_age > 50) | (df.loser_age < 14) | (df.loser_age > 50)).sum())}\n"
        "- (Ids are the join key: the one id with two spellings, Roger-Vasselin, is harmless.)\n")

    # --- ordering + splits --------------------------------------------------
    df["round_rank"] = df["round"].map(ROUND_RANK)
    df["match_id"] = df.tourney_id + "_" + df.match_num.astype(str)
    assert df.match_id.is_unique
    df = df.sort_values(["tourney_date", "round_rank", "tourney_id", "match_num"], kind="stable", ignore_index=True)
    df["split"] = pd.NA
    for lo, hi, name in SPLITS:
        df.loc[df.tourney_date.dt.year.between(lo, hi), "split"] = name
    assert df.split.notna().all()
    assert df.groupby("split").tourney_date.min().loc[[s[2] for s in SPLITS]].is_monotonic_increasing
    assert (df.groupby("tourney_id").split.nunique() == 1).all()  # no tournament straddles two splits

    # --- coverage -----------------------------------------------------------
    yr = df.tourney_date.dt.year
    last = df[df.tourney_date == df.tourney_date.max()]
    top_round = max(last["round"].unique(), key=ROUND_RANK.get)
    log("## Coverage\n\n| Year | Matches |\n|---|---|\n" + "\n".join(f"| {y} | {n:,} |" for y, n in yr.value_counts().sort_index().items()))
    log(f"\n\n| Split | Years | Matches |\n|---|---|---|\n" + "\n".join(
        f"| {n} | {lo}-{hi} | {int((df.split == n).sum()):,} |" for lo, hi, n in SPLITS))
    log(f"\n\n- **Clean matches: {len(df):,}**\n"
        f"- Level counts: {df.tourney_level.value_counts().to_dict()} (G Slam, M Masters, A other tour, D Davis Cup, F Tour Finals, O Olympics)\n"
        f"- Surface counts: {df.surface.value_counts(dropna=False).to_dict()}\n"
        f"- **Latest tourney_date: {df.tourney_date.max().date()}** ({', '.join(last.tourney_name.unique())}); "
        f"furthest round present: {top_round}. Exact per-match dates do not exist in this data, so the true last match day is unknown.\n")

    # --- missing values -----------------------------------------------------
    miss = (df.isna().mean() * 100).round(1)
    miss = miss[miss > 0].sort_values(ascending=False)
    log("## Missing values (% of clean rows; not imputed)\n\n" + ", ".join(f"`{c}` {v}%" for c, v in miss.items()) + "\n")
    st = df.groupby("tourney_level").w_svpt.apply(lambda s: round(s.isna().mean() * 100, 1)).to_dict()
    log(f"- Serve stats missing by tourney_level (%): {st}\n")

    # --- features -----------------------------------------------------------
    log("## Features and leakage rules\n"
        f"- Post-match columns (never usable for the match they describe, only as lagged history): `{POST_MATCH_COLS}`\n"
        "- Pre-match columns: ids, seed, entry, hand, height, age (as of tourney_date), ranks and rank points "
        "(as of the ranking published before tourney_date), surface, tourney_level, draw_size, best_of, round.\n"
        "- `winner_*` / `loser_*` naming reveals the label. Phase 3 must randomise players into A/B before building features.\n"
        "- Visibility rule: a match may use only matches with a strictly smaller (tourney_date, round_rank). "
        "Matches in the same tournament week and round are treated as simultaneous; ratings are updated per group, after predicting it.\n")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUT, index=False, date_format="%Y-%m-%d")
    df[df.split.isin(DEV_SPLITS)].to_csv(DEV_OUT, index=False, date_format="%Y-%m-%d")
    df[~df.split.isin(DEV_SPLITS)].to_csv(LOCKED_OUT, index=False, date_format="%Y-%m-%d")
    REPORT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
