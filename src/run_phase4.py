"""Phase 4: recent-form features + Logistic Regression, compared with the Elo baseline (dev data only).

Run from the project root:  python -m src.run_phase4
Protocol: PLAN.md 'Phase 4 protocol'. 2025/2026 are never read. Hyperparameters come from dev folds 2020-2023 only;
2024 validation is scored once with frozen choices and is NOT used to choose anything.
"""
from pathlib import Path

import numpy as np
import pandas as pd

from src import evaluate as ev
from src import models
from src.canonical import MAX_DAYS, SCORED_LEVELS, load_dev
from src.elo import expected, prob, run_elo
from src.features import build_features, design, elo_ratings
from src.pairs import assign_ab

REPORT = Path("reports/phase4_features_lr.md")
KS = (16, 24, 32, 48)
STEPS = [("B", "elo", ["elo"]), ("B+", "rank", ["elo", "rank"])]
for g in ("last", "win", "surf", "rest", "dec", "adj", "adjdec"):
    STEPS.append((f"+{g}", g, STEPS[-1][2] + [g]))
GROUPS = {n: gr for n, _, gr in STEPS}
NAMES = {"B": "B: LR Elo", "B+": "B+: + ranking", "+dec": "C: + recent form", "+adjdec": "D: + opponent-adjusted"}
f4, f3, sg = (lambda v: f"{v:.4f}"), (lambda v: f"{v:.3f}"), (lambda v: f"{v:+.4f}")


def metrics(y, p):
    return dict(n=len(y), log_loss=ev.log_loss(y, p), brier=ev.brier(y, p), accuracy=ev.accuracy(y, p), ece=ev.ece(y, p))


def diff(y, p_new, p_old, groups):
    return ev.paired_bootstrap(ev.per_match_loss(y, p_new), ev.per_match_loss(y, p_old), groups)


def run_variant(D, y, year, dev, val, oof_rows, groups, sel=None, c_grid=models.C_GRID):
    """Select (half-life, C) on dev folds unless given; return OOF (dev folds) and 2024 predictions from frozen fits."""
    (hl, C), tab = (sel, None) if sel else models.select(D, y, year, dev, groups, c_grid)
    cols = models.columns(groups, hl or 30)
    oof = models.oof_predictions(D, y, year, dev, groups, hl or 30, C)
    tr = dev & (year >= models.TRAIN_FROM)
    m = models.fit(D.loc[tr, cols], y[tr], C)
    return dict(hl=hl, C=C, tab=tab, oof=oof[oof_rows], val=pd.Series(models.predict(m, D.loc[val, cols]), index=D.index[val]), model=m, cols=cols)


def main():
    raw = load_dev()  # dev file only: 2025/2026 are not in memory
    ab = assign_ab(raw).sort_values(["event_date", "round_rank", "match_id"], kind="stable").reset_index(drop=True)
    meta = ab.set_index("match_id")
    year = meta.event_date.dt.year
    elig = meta.level.isin(SCORED_LEVELS) & year.between(2015, 2024)
    dev, val = elig & (year <= 2023), elig & (year == 2024)
    oof_rows = elig & year.isin(models.FOLDS)
    y = meta.y
    L = ["# Phase 4: recent form + Logistic Regression (dev data only; auto-generated by src/run_phase4.py)\n",
         f"Eligible tour-level matches 2015-2024: **{int(elig.sum()):,}** (dev 2015-2023: {int(dev.sum()):,}; validation 2024: {int(val.sum()):,}). "
         "All models are scored on exactly these rows. **2025/2026 were not read.** Primary visibility rule: tournament-completion (PLAN.md M1).\n"]

    # ---- 1. Elo K under the strict rule (dev only) -------------------------------------------------
    rows = []
    for k in KS:
        r = run_elo(ab, k=k, release_days=MAX_DAYS)[0].set_index("match_id").loc[meta.index]
        rows.append((k, ev.log_loss(y[dev], prob(r, 0.0)[dev]), ev.log_loss(y[dev], prob(r, 1.0)[dev])))
    kt = pd.DataFrame(rows, columns=["K", "general Elo dev log loss", "surface Elo dev log loss"])
    k_gen, k_surf = int(kt.loc[kt.iloc[:, 1].idxmin(), "K"]), int(kt.loc[kt.iloc[:, 2].idxmin(), "K"])
    L += ["## 1. Elo K re-selected under the strict rule (dev 2015-2023)\n", ev.md(kt, {c: f4 for c in kt.columns[1:]}),
          f"\nChosen: general K={k_gen}, surface K={k_surf}. (Phase 3 chose 24 and 32 under the group rule.)\n"]

    # ---- 2. features (strict primary, group rule as sensitivity) ----------------------------------------
    rt = elo_ratings(ab, k_gen, k_surf, MAX_DAYS)
    D = design(ab, rt, *build_features(ab, rt, MAX_DAYS)).loc[meta.index]
    assert np.isfinite(D.to_numpy()).all(), "NaN/inf in features"
    rt_g = elo_ratings(ab, k_gen, k_surf, None)
    D_g = design(ab, rt_g, *build_features(ab, rt_g, None)).loc[meta.index]
    pA = pd.Series(expected(rt.loc[meta.index].elo_a.to_numpy(), rt.loc[meta.index].elo_b.to_numpy()), index=meta.index)
    pA_g = pd.Series(expected(rt_g.loc[meta.index].elo_a.to_numpy(), rt_g.loc[meta.index].elo_b.to_numpy()), index=meta.index)

    # ---- 3. models: ablation steps + leave-one-group-out -----------------------------------------------
    R = {}
    for name, _, groups in STEPS:
        R[name] = run_variant(D, y, year, dev, val, oof_rows, groups)
    full = STEPS[-1][2]
    LOO = {g: run_variant(D, y, year, dev, val, oof_rows, [x for x in full if x != g]) for g in full}
    grp = meta.tourney_id
    gv, go = grp[val].to_numpy(), grp[oof_rows].to_numpy()
    yv, yo = y[val], y[oof_rows]
    P = {"A: Elo baseline": (pA[oof_rows], pA[val])} | {NAMES[k]: (R[k]["oof"], R[k]["val"]) for k in NAMES}
    for p_o, p_v in P.values():  # identical eligible rows for every model
        assert p_o.notna().all() and p_v.notna().all() and (p_v.index == P["A: Elo baseline"][1].index).all()

    # ---- main table ---------------------------------------------------------------------------------
    rows = []
    for nm, (p_o, p_v) in P.items():
        for lab, yy, pp in (("dev folds 2020-23 (selection data)", yo, p_o), ("validation 2024", yv, p_v)):
            rows.append({"model": nm, "set": lab} | metrics(yy, pp.to_numpy()))
    L += ["## 2. Main comparison (identical matches for every model)\n",
          "Dev-fold rows were used to choose hyperparameters, so they are optimistic; **validation 2024 is the cleaner read**, but it is not an independent test (2025/2026 are).\n",
          ev.md(pd.DataFrame(rows), {"log_loss": f4, "brier": f4, "accuracy": f3, "ece": f4}), ""]
    hp = pd.DataFrame([(NAMES.get(k, k), R[k]["hl"], R[k]["C"]) for k in R], columns=["model", "decay half-life (days)", "C"])
    L += ["Hyperparameters chosen on dev folds only:\n", ev.md(hp.fillna("-")), ""]

    # ---- bootstrap vs Elo -----------------------------------------------------------------------------
    out = []
    for nm in list(P)[1:]:
        for lab, yy, g, idx in (("dev folds", yo, go, 0), ("validation 2024", yv, gv, 1)):
            m_, lo, hi = diff(yy, P[nm][idx], P["A: Elo baseline"][idx], g)
            out.append((nm, lab, m_, lo, hi, "yes" if hi < 0 else ("worse" if lo > 0 else "no")))
    L += ["## 3. Log-loss difference vs Elo baseline (negative = better), 95% interval, resampled by tournament\n",
          ev.md(pd.DataFrame(out, columns=["model", "set", "diff", "low", "high", "clearly better?"]), {c: sg for c in ("diff", "low", "high")}), ""]

    # ---- cumulative effect of whole blocks (added after the first run; compares already-selected models only) ----
    blocks = [("+ranking (B+ vs B)", "B+", "B"), ("+all recent form (C vs B+)", "+dec", "B+"),
              ("+opponent-adjusted (D vs C)", "+adjdec", "+dec"), ("form + adjusted (D vs B+)", "+adjdec", "B+")]
    out = []
    for lab, new, old in blocks:
        for sl, yy, g, key in (("dev folds", yo, go, "oof"), ("validation 2024", yv, gv, "val")):
            m_, lo, hi = diff(yy, R[new][key], R[old][key], g)
            out.append((lab, sl, m_, lo, hi, "yes" if hi < 0 else ("worse" if lo > 0 else "no")))
    L += ["## 3b. Cumulative effect of each block (negative = better)\n",
          ev.md(pd.DataFrame(out, columns=["block", "set", "diff", "low", "high", "clearly better?"]), {c: sg for c in ("diff", "low", "high")}), ""]

    # ---- does each added group help? ------------------------------------------------------------------
    rows, prev = [], None
    for name, grpname, _ in STEPS:
        o, v = R[name]["oof"], R[name]["val"]
        d_o = diff(yo, o, prev["oof"], go) if prev else (np.nan,) * 3
        d_v = diff(yv, v, prev["val"], gv) if prev else (np.nan,) * 3
        ci = lambda d: "-" if prev is None else f"[{d[1]:+.4f}, {d[2]:+.4f}]"
        rows.append((name, grpname, ev.log_loss(yo, o), d_o[0], ci(d_o), ev.log_loss(yv, v), d_v[0], ci(d_v)))
        prev = R[name]
    ab_tab = pd.DataFrame(rows, columns=["step", "group added", "dev-fold LL", "vs prev", "95% CI", "val LL", "vs prev ", "95% CI "])
    L += ["## 4. Adding feature groups one at a time (each step re-selects C / half-life on dev folds)\n",
          "`vs prev` = change in log loss relative to the step above (negative = better).\n",
          ev.md(ab_tab, {"dev-fold LL": f4, "val LL": f4, "vs prev": lambda v: "-" if pd.isna(v) else sg(v), "vs prev ": lambda v: "-" if pd.isna(v) else sg(v)}), ""]
    rows = []
    for g, r in LOO.items():
        d_o, d_v = diff(yo, r["oof"], R["+adjdec"]["oof"], go), diff(yv, r["val"], R["+adjdec"]["val"], gv)
        rows.append((g, ev.log_loss(yo, r["oof"]), d_o[0], ev.log_loss(yv, r["val"]), d_v[0], f"[{d_v[1]:+.4f}, {d_v[2]:+.4f}]"))
    L += ["Leave-one-group-out from model D (positive = removing the group makes it worse, i.e. the group helped):\n",
          ev.md(pd.DataFrame(rows, columns=["group removed", "dev-fold LL", "vs D", "val LL", "vs D ", "95% CI (val)"]),
                {"dev-fold LL": f4, "val LL": f4, "vs D": sg, "vs D ": sg}), ""]

    # ---- calibration (measured on predictions from models that never saw the evaluated rows) ----------------
    L += ["## 5. Calibration, validation 2024\n",
          "No post-hoc recalibration was applied. Slope < 1 = too extreme (overconfident); intercept is on the logit scale. These are diagnostics, not corrections.\n"]
    cal = []
    for nm in ("A: Elo baseline", NAMES["B"], NAMES["+adjdec"]):
        a_, b_ = ev.calibration_fit(yv, P[nm][1])
        cal.append((nm, ev.ece(yv, P[nm][1]), a_, b_))
    L += [ev.md(pd.DataFrame(cal, columns=["model", "ECE", "intercept", "slope"]), {"ECE": f4, "intercept": f3, "slope": f3}), ""]
    for nm in ("A: Elo baseline", NAMES["+adjdec"]):
        L += [f"Reliability, {nm}:\n", ev.md(ev.reliability(yv, P[nm][1]), {"lo": lambda v: f"{v:.1f}", "hi": lambda v: f"{v:.1f}", "mean_pred": f3, "actual": f3}), ""]

    # ---- impact of the ordering choice ---------------------------------------------------------------------------------
    rows = []
    for nm, key in [("A: Elo baseline", None), (NAMES["B"], "B"), (NAMES["B+"], "B+"), (NAMES["+dec"], "+dec"), (NAMES["+adjdec"], "+adjdec")]:
        if key is None:
            p_o, p_v, q_o, q_v = pA[oof_rows], pA[val], pA_g[oof_rows], pA_g[val]
        else:
            r = run_variant(D_g, y, year, dev, val, oof_rows, GROUPS[key], sel=(R[key]["hl"], R[key]["C"]))
            p_o, p_v, q_o, q_v = R[key]["oof"], R[key]["val"], r["oof"], r["val"]
        d = diff(yv, q_v, p_v, gv)
        rows.append((nm, ev.log_loss(yv, p_v), ev.log_loss(yv, q_v), d[0], f"[{d[1]:+.4f}, {d[2]:+.4f}]", ev.log_loss(yo, p_o), ev.log_loss(yo, q_o)))
    L += ["## 6. Impact of the conservative tournament-completion rule\n",
          "Same hyperparameters, same Elo K; only the visibility rule changes. `group - strict` > 0 means the strict rule scores slightly *better*; < 0 means it costs accuracy.\n",
          ev.md(pd.DataFrame(rows, columns=["model", "val LL strict", "val LL group rule", "group - strict", "95% CI", "dev-fold LL strict", "dev-fold LL group"]),
                {c: f4 for c in ("val LL strict", "val LL group rule", "dev-fold LL strict", "dev-fold LL group")} | {"group - strict": sg}), ""]

    # ---- model D coefficients ------------------------------------------------------------------------------------
    sc, lr = R["+adjdec"]["model"]
    co = pd.DataFrame({"feature": R["+adjdec"]["cols"], "coef per 1 SD": lr.coef_[0]}).sort_values("coef per 1 SD", key=abs, ascending=False)
    L += ["## 7. Model D coefficients (per standardised unit; features are correlated, so read signs cautiously)\n", ev.md(co.head(12), {"coef per 1 SD": f3}), ""]
    REPORT.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
