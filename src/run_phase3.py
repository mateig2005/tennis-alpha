"""Phase 3: Elo baselines on DEV data only (warmup 2010-14, train 2015-23, validation 2024).

Run from the project root:  python -m src.run_phase3
2025 (test) and 2026 (forward_oos) are not read: they live in a separate file (see PLAN.md section 8).
Settings are chosen on 'train' (2015-2023) log loss; 'validation' (2024) is then scored once with the frozen choice.
"""
import itertools
from pathlib import Path

import numpy as np
import pandas as pd

from src import evaluate as ev
from src.canonical import MAX_DAYS, SCORED_LEVELS, load_dev
from src.elo import prob, run_elo
from src.pairs import assign_ab

REPORT = Path("reports/phase3_elo.md")
K_GRID, W_GRID = (16, 24, 32, 48), (0.0, 0.25, 0.5, 0.75, 1.0)
UPDATE_GRID = {"all levels": None, "tour-level only": SCORED_LEVELS}
FAMILY = {"Standard Elo": (0.0,), "Surface Elo": (1.0,), "Blend (general+surface)": (0.25, 0.5, 0.75)}


def md(df, fmt=None):
    fmt = fmt or {}
    cols = list(df.columns)
    rows = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        rows.append("| " + " | ".join(fmt.get(c, lambda v: f"{v}")(v) for c, v in zip(cols, r)) + " |")
    return "\n".join(rows)


def overlap_diagnostic(df):
    """Share of a player's consecutive tournaments whose nominal windows overlap (start of next < start + max length)."""
    long = pd.concat([df[["winner_id", "tourney_id", "event_date", "level"]].set_axis(["p", "t", "d", "lv"], axis=1),
                      df[["loser_id", "tourney_id", "event_date", "level"]].set_axis(["p", "t", "d", "lv"], axis=1)])
    long = long.drop_duplicates(["p", "t"]).sort_values(["p", "d", "t"])
    nxt = long.groupby("p").d.shift(-1)
    ends = long.d + pd.to_timedelta(long.lv.map(MAX_DAYS), unit="D")
    ok = nxt.notna()
    return int((nxt[ok] < ends[ok]).sum()), int(ok.sum())


def main():
    raw = load_dev()
    ab = assign_ab(raw).sort_values(["event_date", "round_rank", "match_id"], kind="stable").reset_index(drop=True)
    scored = ab.level.isin(SCORED_LEVELS)
    dev, val = (ab.split == "train") & scored, (ab.split == "validation") & scored
    year = ab.event_date.dt.year
    L = ["# Phase 3: Elo baselines (dev data only; auto-generated by src/run_phase3.py)\n",
         f"Rows read: {len(ab):,} (warmup {int((ab.split=='warmup').sum()):,}, train {int((ab.split=='train').sum()):,}, "
         f"validation {int((ab.split=='validation').sum()):,}). **2025 and 2026 were not read.** "
         f"Scored: tour-level A/M/G/F only -> dev {int(dev.sum()):,} matches, validation {int(val.sum()):,}.\n"]

    # ---- 1. grid on dev --------------------------------------------------------------------------
    results, runs = [], {}
    for (uname, ulev), k in itertools.product(UPDATE_GRID.items(), K_GRID):
        r, _ = run_elo(ab, k=k, update_levels=ulev)
        r = r.set_index("match_id").loc[ab.match_id].reset_index()
        runs[(uname, k)] = r
        for w in W_GRID:
            p = prob(r, w).to_numpy()
            results.append((uname, k, w, ev.log_loss(ab.y[dev], p[dev]), ev.log_loss(ab.y[val], p[val])))
    grid = pd.DataFrame(results, columns=["update", "K", "w", "dev_logloss", "val_logloss"])
    best = {}
    for fam, ws in FAMILY.items():
        g = grid[grid.w.isin(ws)].sort_values("dev_logloss").iloc[0]
        best[fam] = g
    L += ["## 1. Settings chosen on dev (2015-2023) log loss\n",
          "`w` = weight on surface rating (0 = standard Elo, 1 = surface Elo). Validation column is shown for transparency but **not** used to choose.\n",
          md(grid.sort_values("dev_logloss").head(10), {"dev_logloss": lambda v: f"{v:.4f}", "val_logloss": lambda v: f"{v:.4f}", "w": lambda v: f"{v:.2f}"}),
          "\nChosen (best dev log loss within each family):\n",
          md(pd.DataFrame(best).T[["update", "K", "w", "dev_logloss"]].reset_index(names="model"),
             {"dev_logloss": lambda v: f"{float(v):.4f}"}), ""]

    # ---- 2. frozen models on dev and validation ----------------------------------------------------
    b = ev.fit_rank_baseline(ab.rank_a[dev], ab.rank_b[dev], ab.y[dev])  # fitted on dev only
    P = {"Always 50%": np.full(len(ab), 0.5), "Rank baseline": ev.rank_prob(b, ab.rank_a, ab.rank_b)}
    for fam, g in best.items():
        P[fam] = prob(runs[(g["update"], int(g.K))], float(g.w)).to_numpy()
    rows = []
    for name, p in P.items():
        for lab, m in (("dev 2015-23", dev), ("validation 2024", val)):
            y = ab.y[m]
            rows.append((name, lab, int(m.sum()), ev.log_loss(y, p[m]), ev.brier(y, p[m]), ev.accuracy(y, p[m]), ev.ece(y, p[m])))
    tab = pd.DataFrame(rows, columns=["model", "set", "n", "log_loss", "brier", "accuracy", "ece"])
    f4, f3 = (lambda v: f"{v:.4f}"), (lambda v: f"{v:.3f}")
    L += [f"## 2. Results (rank baseline: b = {b:.3f}, unranked = rank {ev.UNRANKED})\n",
          "Always-50% scores log loss 0.6931 and Brier 0.2500 by construction. Lower is better for log loss, Brier and ECE.\n",
          md(tab, {"log_loss": f4, "brier": f4, "accuracy": f3, "ece": f4}), ""]

    # ---- 3. is the difference real? paired bootstrap on validation ---------------------------------
    loss = {k: ev.per_match_loss(ab.y[val], v[val]) for k, v in P.items()}
    grp = ab.tourney_id[val].to_numpy()
    pairs = [("Standard Elo", "Always 50%"), ("Standard Elo", "Rank baseline"), ("Surface Elo", "Standard Elo"),
             ("Blend (general+surface)", "Standard Elo")]
    out = []
    for a_, b_ in pairs:
        m_, lo, hi = ev.paired_bootstrap(loss[a_], loss[b_], grp)
        out.append((f"{a_} minus {b_}", m_, lo, hi, "yes" if hi < 0 else ("worse" if lo > 0 else "no (interval includes 0)")))
    L += ["## 3. Validation 2024: log-loss difference with 95% interval (resampled by tournament)\n",
          "Negative = first model better. 'Clear' only if the whole interval is below 0.\n",
          md(pd.DataFrame(out, columns=["comparison", "diff", "low", "high", "clearly better?"]),
             {"diff": lambda v: f"{v:+.4f}", "low": lambda v: f"{v:+.4f}", "high": lambda v: f"{v:+.4f}"}), ""]

    # ---- 3b. sensitivity: strict visibility for overlapping tournaments ---------------------------
    sens = []
    for name, fam in (("Standard Elo", "Standard Elo"), ("Blend (general+surface)", "Blend (general+surface)")):
        g = best[fam]
        rs, _ = run_elo(ab, k=int(g.K), update_levels=UPDATE_GRID[g["update"]], release_days=MAX_DAYS)
        ps = prob(rs.set_index("match_id").loc[ab.match_id].reset_index(), float(g.w)).to_numpy()
        m_, lo, hi = ev.paired_bootstrap(ev.per_match_loss(ab.y[val], ps[val]), loss[name], grp)
        sens.append((name, ev.log_loss(ab.y[dev], P[name][dev]), ev.log_loss(ab.y[dev], ps[dev]),
                     ev.log_loss(ab.y[val], P[name][val]), ev.log_loss(ab.y[val], ps[val]), m_, lo, hi))
    L += ["## 3b. Sensitivity: strict visibility (results released only after the tournament's maximum length)\n",
          f"Same settings, but a result is invisible to everything until `event_date + {MAX_DAYS}` days (by level) has passed, even inside its own tournament. "
          "This is the safest reading of the unknown dates; it costs the within-tournament information. A small gap means the round-order assumption barely matters.\n",
          md(pd.DataFrame(sens, columns=["model", "dev group rule", "dev strict", "val group rule", "val strict", "val strict - group", "low", "high"]),
             {c: f4 for c in ("dev group rule", "dev strict", "val group rule", "val strict")} | {c: (lambda v: f"{v:+.4f}") for c in ("val strict - group", "low", "high")}), ""]

    # ---- 4. stability by year ------------------------------------------------------------------
    yrs = []
    for y_ in range(2015, 2025):
        m = scored & (year == y_)
        yrs.append((y_, int(m.sum())) + tuple(ev.log_loss(ab.y[m], P[k][m]) for k in ("Always 50%", "Rank baseline", "Standard Elo", "Blend (general+surface)")))
    L += ["## 4. Log loss by year (settings frozen from dev)\n",
          md(pd.DataFrame(yrs, columns=["year", "n", "50%", "rank", "std Elo", "blend"]), {c: f4 for c in ("50%", "rank", "std Elo", "blend")}), ""]

    # ---- 5. calibration (validation) -----------------------------------------------------------
    for name in ("Standard Elo", "Blend (general+surface)"):
        r = ev.reliability(ab.y[val], P[name][val])
        L += [f"## 5. Calibration on validation: {name}\n",
              "Of the matches given probability near `mean_pred`, `actual` is how often A really won.\n",
              md(r, {"lo": lambda v: f"{v:.1f}", "hi": lambda v: f"{v:.1f}", "mean_pred": f3, "actual": f3}), ""]

    # ---- 6. diagnostics ------------------------------------------------------------------------
    n_ov, n_all = overlap_diagnostic(raw)
    pairs_in_group = ab.groupby(["event_date", "round_rank"]).size()
    L += ["## 6. Diagnostics\n",
          f"- Consecutive tournament pairs per player whose nominal windows overlap (dev data): {n_ov:,} of {n_all:,} ({100*n_ov/n_all:.1f}%). "
          "Most are legitimate (lost early in a 2-week event, then played the next); the rule is only violated if a player's true order is the reverse of start-date order.",
          f"- Simultaneity groups: {len(pairs_in_group):,}; largest group {int(pairs_in_group.max())} matches. "
          "Group-wise updating makes a match blind to same-round results.",
          f"- A/B balance: A won {100*ab.y.mean():.1f}% of dev matches (should be ~50%).\n"]
    REPORT.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
