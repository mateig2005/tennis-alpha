"""Phase 5: XGBoost on the Model D features, diagnostics, rank-independent candidate, and the freeze.

Run from the project root:  python -m src.run_phase5
Protocol: PLAN.md 'Phase 5 protocol'. Reads the dev file only. Every choice (tuning, early stopping, ablation,
importance, primary algorithm) uses dev folds 2020-2023. 2024 is reported once and chooses nothing.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

from src import diagnostics as dg
from src import evaluate as ev
from src import gbm, models
from src.canonical import MAX_DAYS
from src.dataset import ELO_K_GEN, ELO_K_SURF, load_design
from src.features import PRIOR
from src.run_phase4 import GROUPS, run_variant

REPORT, FROZEN = Path("reports/phase5_xgboost.md"), Path("models/frozen_phase5.json")
C_WIDE = (0.001, 0.003, 0.01, 0.03, 0.1, 1.0, 10.0, 100.0)  # PLAN.md N4
FULL = GROUPS["+adjdec"]                                    # Model D feature groups
NORANK = [g for g in FULL if g != "rank"]                   # rank-independent Model D (PLAN.md N6)
LR_SPECS = {"B+ LR": GROUPS["B+"], "C LR": GROUPS["+dec"], "D LR": FULL, "D-norank LR": NORANK}
f4, f3, sg = (lambda v: f"{v:.4f}"), (lambda v: f"{v:.3f}"), (lambda v: f"{v:+.4f}")
BANDS = ["1: top 10", "2: 11-30", "3: 31-100", "4: 100+/unranked"]


def diff(y, p_new, p_old, groups):
    return ev.paired_bootstrap(ev.per_match_loss(y, p_new), ev.per_match_loss(y, p_old), groups)


def verdict(lo, hi):
    return "yes" if hi < 0 else ("worse" if lo > 0 else "no")


def main():
    S = load_design()
    D, y, year = S.D, S.y, S.year
    yo, yv, go, gv = y[S.oof], y[S.val], S.tourney[S.oof].to_numpy(), S.tourney[S.val].to_numpy()
    L = ["# Phase 5: XGBoost on Model D, diagnostics and freeze (dev data only; auto-generated by src/run_phase5.py)\n",
         f"Eligible matches: dev folds 2020-2023 = {int(S.oof.sum()):,} (all choices made here); validation 2024 = {int(S.val.sum()):,} "
         "(reported once, chooses nothing). **2025/2026 were not read.**\n"]

    # ---- 1. Logistic Regression, wider C grid ---------------------------------------------------------
    LR = {n: run_variant(D, y, year, S.dev, S.val, S.oof, g, c_grid=C_WIDE) for n, g in LR_SPECS.items()}
    hl, c_d = LR["D LR"]["hl"], LR["D LR"]["C"]
    L += ["## 1. Logistic Regression re-selected with the wider C grid (dev folds)\n",
          ev.md(pd.DataFrame([(n, r["hl"] or "-", r["C"], "yes" if r["C"] in (C_WIDE[0], C_WIDE[-1]) else "no") for n, r in LR.items()],
                             columns=["model", "half-life (days)", "C", "on grid edge?"])), ""]

    # ---- 2. XGBoost tuning on dev folds -----------------------------------------------------------------
    cols_d, cols_n = models.columns(FULL, hl), models.columns(NORANK, hl)
    cfg, grid, grid_p = gbm.select(D, y, year, S.dev, cols_d)

    def xgb_variant(cols):
        o, folds, trees = gbm.oof(D, y, year, S.dev, cols, cfg)
        final, n = gbm.train(D, y, year, S.dev, cols, cfg, 2023)  # trees chosen on 2023, fitted on 2015-2023; 2024 unseen
        return dict(oof=o[S.oof], val=pd.Series(gbm.predict(final, D.loc[S.val, cols]), index=D.index[S.val]), folds=folds, trees=trees, model=final, n=n, cols=cols)

    XD, XN = xgb_variant(cols_d), xgb_variant(cols_n)
    L += ["## 2. XGBoost settings (dev folds; early stopping inside each training period)\n",
          ev.md(grid.drop(columns="id").sort_values("mean_logloss"), {"mean_logloss": f4, "mean_trees": lambda v: f"{v:.0f}"}),
          f"\nChosen (simplest within {gbm.TOLERANCE} of the best): **{cfg}**. Trees per fold: {XD['trees']}; final model (fit 2015-2023): {XD['n']} trees.\n"]

    P = {"A Elo": (S.p_elo[S.oof], S.p_elo[S.val])} | {n: (r["oof"], r["val"]) for n, r in LR.items()}
    P |= {"D XGB": (XD["oof"], XD["val"]), "D-norank XGB": (XN["oof"], XN["val"])}
    for o, v in P.values():
        assert o.notna().all() and v.notna().all() and (o.index == P["A Elo"][0].index).all() and (v.index == P["A Elo"][1].index).all()

    # ---- 3. main comparison -----------------------------------------------------------------------------
    rows = []
    for n, (o, v) in P.items():
        for lab, yy, pp in (("dev folds 2020-23", yo, o), ("validation 2024", yv, v)):
            rows.append(dict(model=n, set=lab, n=len(yy), log_loss=ev.log_loss(yy, pp), brier=ev.brier(yy, pp), accuracy=ev.accuracy(yy, pp),
                             ece=ev.ece(yy, pp), slope=ev.calibration_fit(yy, pp)[1]))
    L += ["## 3. Main comparison (identical matches for every model)\n",
          "Dev folds were used for selection (optimistic). 2024 chose nothing in this phase, but it is not an independent test. `slope` < 1 = overconfident.\n",
          ev.md(pd.DataFrame(rows), {"log_loss": f4, "brier": f4, "accuracy": f3, "ece": f4, "slope": f3}), ""]

    # ---- 4. differences with uncertainty ----------------------------------------------------------------
    comps = [(n, "A Elo") for n in list(P)[1:]] + [("D XGB", "D LR"), ("D LR", "C LR"), ("D LR", "B+ LR"), ("D XGB", "B+ LR"),
                                                   ("D-norank LR", "D LR"), ("D-norank XGB", "D XGB")]
    rows = []
    for new, old in comps:
        for lab, yy, g, i in (("dev folds", yo, go, 0), ("validation 2024", yv, gv, 1)):
            m_, lo, hi = diff(yy, P[new][i], P[old][i], g)
            rows.append((f"{new} minus {old}", lab, m_, lo, hi, verdict(lo, hi)))
    L += ["## 4. Log-loss differences, 95% interval resampled by tournament (negative = first model better)\n",
          ev.md(pd.DataFrame(rows, columns=["comparison", "set", "diff", "low", "high", "clearly better?"]), {c: sg for c in ("diff", "low", "high")}), ""]

    # ---- 5. primary algorithm for D (rule N9, dev folds) ---------------------------------------------------
    m_, lo, hi = diff(yo, XD["oof"], LR["D LR"]["oof"], go)
    primary = "D XGB" if hi < 0 else "D LR"
    nr_primary = "D-norank XGB" if primary == "D XGB" else "D-norank LR"
    L += ["## 5. Primary algorithm for Model D (rule fixed in PLAN.md N9, decided on dev folds)\n",
          f"XGBoost D minus LR D on dev folds: {m_:+.4f} [{lo:+.4f}, {hi:+.4f}]. Rule: XGBoost is primary only if the interval is entirely below 0. "
          f"**Primary: {primary}.** Rank-independent counterpart: {nr_primary}.\n"]

    # ---- 6. nonlinearity and interactions (dev folds) -------------------------------------------------------
    b1 = grid[grid.max_depth == 1].sort_values("mean_logloss").iloc[0]
    b2 = grid[grid.max_depth > 1].sort_values("mean_logloss").iloc[0]
    p1, p2 = grid_p[int(b1.id)][S.oof], grid_p[int(b2.id)][S.oof]
    r1, r2 = diff(yo, p1, LR["D LR"]["oof"], go), diff(yo, p2, p1, go)
    L += ["## 6. Nonlinear effects and interactions (dev folds)\n",
          "Depth-1 trees can bend each feature's effect but cannot combine features; deeper trees can. Comparing them isolates the two.\n",
          ev.md(pd.DataFrame([("Nonlinearity: best depth-1 XGBoost minus LR D", r1[0], r1[1], r1[2], verdict(r1[1], r1[2])),
                              (f"Interactions: best depth-{int(b2.max_depth)} minus best depth-1", r2[0], r2[1], r2[2], verdict(r2[1], r2[2]))],
                             columns=["question", "diff", "low", "high", "clearly better?"]), {c: sg for c in ("diff", "low", "high")}), ""]

    # ---- 7. multicollinearity (dev rows) -------------------------------------------------------------------
    X = D.loc[S.dev, cols_d]
    v = dg.vif(X).sort_values(ascending=False)
    L += ["## 7. Multicollinearity among Model D features (dev rows)\n",
          "VIF = how much a feature is explained by the others (1 = not at all; above ~10 = heavily). High VIF makes individual LR coefficients unstable, not the predictions.\n",
          ev.md(v.head(10).rename_axis("feature").reset_index(name="VIF"), {"VIF": lambda x: f"{x:.1f}"}),
          f"\nFeatures with VIF > 10: {int((v > 10).sum())} of {len(v)}. Pairs with |r| >= 0.8:\n",
          ev.md(dg.top_correlations(X), {"r": f3}), ""]

    # ---- 8. importance -------------------------------------------------------------------------------------
    gain = pd.Series(XD["model"].get_booster().get_score(importance_type="total_gain"))
    gain.index = [cols_d[int(k[1:])] for k in gain.index]
    gain = (gain / gain.sum()).sort_values(ascending=False)
    gc = {g: models.group_columns(hl)[g] for g in FULL}
    te = {f: S.dev & (year == f) for f in models.FOLDS}
    xf = [(lambda Z, m=XD["folds"][f]: gbm.predict(m, Z[cols_d]), D.loc[te[f], cols_d], y[te[f]].to_numpy()) for f in models.FOLDS]
    lf = []
    for f in models.FOLDS:
        tr = S.dev & (year >= models.TRAIN_FROM) & (year < f)
        m = models.fit(D.loc[tr, cols_d], y[tr], c_d)
        lf.append((lambda Z, m=m: models.predict(m, Z[cols_d]), D.loc[te[f], cols_d], y[te[f]].to_numpy()))
    px, pl = dg.group_permutation(xf, gc), dg.group_permutation(lf, gc)
    imp = pd.DataFrame({"group": FULL, "LR D": [pl[g] for g in FULL], "XGBoost D": [px[g] for g in FULL]}).sort_values("XGBoost D", ascending=False)
    L += ["## 8. Feature importance\n", "XGBoost share of total gain (final model, training data 2015-2023), top 10:\n",
          ev.md(gain.head(10).rename_axis("feature").reset_index(name="gain share"), {"gain share": f3}),
          "\nGroup permutation importance on dev folds: rise in log loss when the whole group is shuffled in held-out data (0 = unused):\n",
          ev.md(imp, {"LR D": sg, "XGBoost D": sg}), ""]

    # ---- 9. ablation: leave one group out (dev folds, hyperparameters fixed) ----------------------------------
    rows = []
    for g in FULL:
        rest = [x for x in FULL if x != g]
        a = diff(yo, models.oof_predictions(D, y, year, S.dev, rest, hl, c_d)[S.oof], LR["D LR"]["oof"], go)
        b = diff(yo, gbm.oof(D, y, year, S.dev, models.columns(rest, hl), cfg)[0][S.oof], XD["oof"], go)
        rows.append((g, a[0], f"[{a[1]:+.4f}, {a[2]:+.4f}]", "yes" if a[1] > 0 else "no", b[0], f"[{b[1]:+.4f}, {b[2]:+.4f}]", "yes" if b[1] > 0 else "no"))
    L += ["## 9. Ablation: remove one group from Model D (dev folds only; positive = the group was helping)\n",
          ev.md(pd.DataFrame(rows, columns=["group removed", "LR D change", "95% CI", "group clearly helps?", "XGB D change", "95% CI ", "group clearly helps? "]),
                {"LR D change": sg, "XGB D change": sg}), ""]

    # ---- 10. subgroups (descriptive) -------------------------------------------------------------------------
    best = np.fmin(S.meta.rank_a, S.meta.rank_b)
    band = pd.cut(best, [0, 10, 30, 100, np.inf], labels=BANDS[:3] + [BANDS[3]]).astype(object).fillna(BANDS[3])
    show = ["A Elo", "B+ LR", "C LR", "D LR", "D XGB", nr_primary]
    L += ["## 10. Log loss by subgroup (descriptive; chooses nothing)\n"]
    for title, lab in (("Surface", S.meta.surface.fillna("Unknown")), ("Season", year.astype(str)), ("Strength band (best ranking of the two players)", band)):
        for sl, mask, i in (("dev folds 2020-23", S.oof, 0), ("validation 2024", S.val, 1)):
            if title == "Season" and i == 1:
                continue
            t = dg.by_group(y[mask], {n: P[n][i] for n in show}, lab[mask])
            L += [f"{title}, {sl}:\n", ev.md(t, {n: f4 for n in show}), ""]

    # ---- 11. calibration of the primary model, validation ---------------------------------------------------------
    L += [f"## 11. Reliability on validation 2024: {primary}\n",
          ev.md(ev.reliability(yv, P[primary][1]), {"lo": lambda x: f"{x:.1f}", "hi": lambda x: f"{x:.1f}", "mean_pred": f3, "actual": f3}), ""]

    # ---- 12. freeze ----------------------------------------------------------------------------------------------
    frozen = {
        "status": "FROZEN at end of Phase 5. Do not change before the independent 2025 / 2026 evaluation.",
        "data": {"source": "sackmann (dev file only)", "visibility": "tournament-completion", "release_days": MAX_DAYS},
        "elo": {"k_general": ELO_K_GEN, "k_surface": ELO_K_SURF, "init": 1500}, "form_prior_matches": PRIOR, "decay_half_life_days": hl,
        "ab_seed": 2024, "train_from_year": models.TRAIN_FROM, "primary": primary, "rank_independent_primary": nr_primary,
        "models": {n: {"type": "logistic_regression", "features": r["cols"], "C": r["C"], "half_life": r["hl"]} for n, r in LR.items()}
        | {"D XGB": {"type": "xgboost", "features": cols_d, "params": gbm.FIXED | cfg, "n_trees": XD["n"]},
           "D-norank XGB": {"type": "xgboost", "features": cols_n, "params": gbm.FIXED | cfg, "n_trees": XN["n"]},
           "A Elo": {"type": "elo", "k": ELO_K_GEN}},
        "xgboost_symmetry": "train on mirrored rows; predict (f(x) + 1 - f(-x)) / 2",
    }
    FROZEN.parent.mkdir(exist_ok=True)
    FROZEN.write_text(json.dumps(frozen, indent=2))
    L += ["## 12. Freeze\n", f"Specification written to `{FROZEN}`: features, Elo settings, half-life {hl}, LR C values, XGBoost settings and tree counts.\n"]
    REPORT.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
